INSERT INTO SYNWMS.RPT_DAILY_STK (
       BASE_YMD,
       WH_CD,
       ITEM_CD,
       END_QTY,
       RNK_NO
     )
SELECT s.LAST_TRX_YMD,
       s.WH_CD,
       s.ITEM_CD,
       SUM(s.ONHAND_QTY) OVER (PARTITION BY s.WH_CD ORDER BY s.ITEM_CD),
       ROW_NUMBER() OVER (PARTITION BY s.WH_CD ORDER BY s.ONHAND_QTY DESC)
  FROM SYNWMS.STK_ONHAND s;
